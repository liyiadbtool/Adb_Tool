# -*- coding: utf-8 -*-
"""T14b：手册补文件页新交互。"""
import io

P = r"C:\Users\SunWwei\Desktop\Adb_Tool\docs\用户使用手册.md"
s = io.open(P, encoding="utf-8").read()

old = """| 从资源管理器拖进本页 | 上传到设备当前目录 |"""
new = """| 从资源管理器拖进本页 | 上传到设备当前目录 |

### 7.3 右键菜单与批量操作（2026-11-19）

在文件行的任意位置**单击右键**，弹出菜单（点空白处或按 `Esc` 关闭）：

| 菜单项 | 说明 |
|---|---|
| **下载到本机** / **上传到设备** | 动作按当前栏决定：设备栏给"下载"，电脑栏给"上传"。目标目录取**对侧当前目录** |
| **重命名** | 只对单个条目可用（多选时置灰） |
| **删除** | 对选中的全部条目生效，会先弹确认框 |
| **复制路径** | 把选中项的完整路径复制到剪贴板（多选取多行） |
| **新建文件夹** | 建在**当前目录**；电脑栏需要先展开某个盘符 |
| **排序：名称 / 大小 / 时间** | 点一次升序，再点同一个字段切降序；当前字段会显示 `↑` / `↓` |
| **显示隐藏文件** | 打开后列出 `.` 开头的条目（默认隐藏） |
| **刷新** | 重新读取当前目录 |

### 7.4 多选

| 操作 | 效果 |
|---|---|
| 单击 | 只选这一项 |
| `Ctrl` + 单击 | 加选 / 取消加选 |
| `Shift` + 单击 | 从上次单击的位置**连选**一段（按屏幕上看到的顺序，隐藏文件过滤后也不会错位） |

多选后拖拽、删除、复制路径都按整批处理。

### 7.5 路径栏双击可编辑

面包屑那一行**双击**会变成一个输入框：

- 输入 `/data/local/tmp` 这类路径，按 `Enter` 直接跳过去；
- `Esc` 或点到别处取消，面包屑自动还原；
- 设备栏和电脑栏各自独立。

> 为什么不做常驻输入框：面包屑本身可点，再并排一个输入框会把搜索框挤没。"""
assert s.count(old) == 1, "手册锚点没匹配上"
s = s.replace(old, new)
io.open(P, "w", encoding="utf-8", newline="\n").write(s)
print("手册已补 7.3–7.5")
